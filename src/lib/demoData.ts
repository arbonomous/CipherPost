/**
 * Generates 50,000 lightweight threads instantaneously so users can verify 120fps
 * TanStack Virtual scrolling with zero layout shift.
 */
export function generateBenchmarkThreads(count: number): ThreadSummary[] {
  const accounts = ['acc-proton-vault', 'acc-work-gmail', 'acc-icloud-personal'];
  const pgpModes: PgpStatus[] = ['none', 'none', 'none', 'signed_verified', 'encrypted'];
  const out: ThreadSummary[] = new Array(count);

  for (let i = 0; i < count; i++) {
    const sender = SYNTHETIC_SENDERS[i % SYNTHETIC_SENDERS.length];
    const subj = SYNTHETIC_SUBJECTS[i % SYNTHETIC_SUBJECTS.length];
    const acc = accounts[i % accounts.length];
    const trackers = i % 3 === 0 ? (i % 6) + 1 : 0;
    const pgp = pgpModes[i % pgpModes.length];

    out[i] = {
      id: `bench-${i}`,
      accountId: acc,
      folderRole: 'inbox',
      subject: `${subj} [#${(count - i).toString().padStart(5, '0')}]`,
      snippet: `Synthetic benchmark message #${i + 1} — sanitized in Rust via lol_html, indexed in SQLCipher FTS5, and virtualized at 120fps with zero layout shift.`,
      participants: [{ name: sender[0], email: sender[1] }],
      lastSenderName: sender[0],
      lastSenderEmail: sender[1],
      messageCount: (i % 4) + 1,
      unreadCount: i < 45 ? 1 : 0,
      isStarred: i % 17 === 0,
      hasAttachments: i % 5 === 0,
      pgpStatus: pgp,
      trackersBlocked: trackers,
      snoozedUntil: null,
      lastMessageAt: NOW - 45000 - i * 420,
    };
  }
  return out;
}

